
BEGIN;
CREATE TABLE students (
    isu_id integer PRIMARY KEY CHECK (isu_id BETWEEN 100000 AND 999999),
    full_name varchar(100) NOT NULL CHECK (char_length(btrim(full_name)) BETWEEN 5 AND 100),
    study_group varchar(5) NOT NULL CHECK (study_group ~ '^[A-Z][0-9]{4}$'),
    dormitory integer NOT NULL CHECK (dormitory BETWEEN 1 AND 99),
    room integer NOT NULL CHECK (room BETWEEN 1 AND 9999),
    settlement_date date NOT NULL CHECK (settlement_date >= DATE '2000-01-01'),
    is_foreigner boolean NOT NULL,
    notes varchar(500) NOT NULL DEFAULT ''
);
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL CONSTRAINT users_username_unique UNIQUE,
    email varchar(254) NOT NULL CONSTRAINT users_email_unique UNIQUE,
    password_hash varchar(100) NOT NULL,
    role varchar(10) NOT NULL CHECK (role IN ('USER', 'ADMIN'))
);
CREATE TABLE refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash varchar(64) NOT NULL UNIQUE,
    user_id bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked boolean NOT NULL DEFAULT false
);
CREATE INDEX refresh_tokens_user_idx ON refresh_tokens(user_id);
COMMIT;
